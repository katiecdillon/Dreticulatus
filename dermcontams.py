def parse_gff_full(path):
    genes = {}
    transcripts = {}
    exons_by_tx = defaultdict(list)
    cds_by_tx = defaultdict(list)
    tx_to_gene = {}

    with open_maybe_gz(path) as f:
        for line in f:
            if not line or line.startswith("#"):
                continue
            parts = line.strip().split("\t")
            if len(parts) != 9:
                continue

            seqid, source, ftype, start, end, score, strand, phase, attrs = parts
            start = int(start)
            end = int(end)

            attr_dict = {}
            for item in attrs.split(";"):
                if "=" in item:
                    k,v = item.split("=",1)
                    attr_dict[k.strip()] = v.strip()

            if ftype == "gene":
                gid = attr_dict.get("ID")
                if gid:
                    genes[gid] = (start, end)

            if ftype in ("mRNA", "transcript"):
                tid = attr_dict.get("ID")
                parent = attr_dict.get("Parent")
                if tid:
                    transcripts[tid] = (start, end)
                    if parent:
                        tx_to_gene[tid] = parent

            if ftype == "exon":
                parent = attr_dict.get("Parent")
                if parent:
                    exons_by_tx[parent].append((start,end))

            if ftype == "CDS":
                parent = attr_dict.get("Parent")
                if parent:
                    cds_by_tx[parent].append((start,end))

    return genes, transcripts, exons_by_tx, cds_by_tx, tx_to_gene


def compute_stats(path):
    genes, transcripts, exons_by_tx, cds_by_tx, tx_to_gene = parse_gff_full(path)

    gene_lengths = [(e - s + 1) for s,e in genes.values()]
    tx_lengths = [(e - s + 1) for s,e in transcripts.values()]

    exon_counts = [len(exons_by_tx[tx]) for tx in transcripts]
    cds_lengths = []
    single_exon = 0

    for tx in transcripts:
        exons = exons_by_tx.get(tx, [])
        cds = cds_by_tx.get(tx, [])

        if len(exons) == 1:
            single_exon += 1

        cds_total = sum((e - s + 1) for s,e in cds)
        if cds_total > 0:
            cds_lengths.append(cds_total)

    return {
        "File": os.path.basename(path),
        "Total genes": len(genes),
        "Total transcripts": len(transcripts),
        "Mean gene length": np.mean(gene_lengths) if gene_lengths else 0,
        "Median gene length": np.median(gene_lengths) if gene_lengths else 0,
        "Mean exons per transcript": np.mean(exon_counts) if exon_counts else 0,
        "Median exons per transcript": np.median(exon_counts) if exon_counts else 0,
        "Mean CDS length": np.mean(cds_lengths) if cds_lengths else 0,
        "Median CDS length": np.median(cds_lengths) if cds_lengths else 0,
        "Single-exon transcripts (%)":
            (single_exon / len(transcripts) * 100) if transcripts else 0
    }


