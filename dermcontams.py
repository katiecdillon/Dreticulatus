def open_maybe_gz(path):
    return gzip.open(path, "rt") if path.endswith(".gz") else open(path, "rt")

def parse_attrs(attr_str):
    # GFF3: key=value;key2=value2
    d = {}
    for part in attr_str.strip().split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            d[k.strip()] = v.strip()
    return d

def read_gff_intervals(path, feature_type="gene", keep_strand=False):
    """
    Returns a PyRanges object with columns:
      Chromosome, Start, End, (optional Strand)
    Note: GFF is 1-based inclusive. PyRanges uses 0-based half-open.
    """
    rows = []
    with open_maybe_gz(path) as f:
        for line in f:
            if not line or line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 9:
                continue
            seqid, source, ftype, start, end, score, strand, phase, attrs = parts
            if ftype != feature_type:
                continue

            start_i = int(start)
            end_i = int(end)

            # Convert 1-based inclusive -> 0-based half-open
            # [start_i, end_i] -> [start_i-1, end_i)
            rows.append({
                "Chromosome": seqid,
                "Start": start_i - 1,
                "End": end_i,
                "Strand": strand
            })

    df = pd.DataFrame(rows)
    if df.empty:
        # return empty PyRanges with correct columns
        if keep_strand:
            return pr.PyRanges(pd.DataFrame(columns=["Chromosome","Start","End","Strand"]))
        return pr.PyRanges(pd.DataFrame(columns=["Chromosome","Start","End"]))

    if not keep_strand:
        df = df[["Chromosome","Start","End"]]
    else:
        df = df[["Chromosome","Start","End","Strand"]]

    return pr.PyRanges(df)

